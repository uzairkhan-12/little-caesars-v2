const PHRASE_KEYS = Object.keys(PHRASES).sort((a, b) => b.length - a.length);

export function translateLabel(text: string, lang: Lang): string {
  if (lang !== "ar" || !text) return text;
  const trimmed = text.trim();
  if (PHRASES[trimmed]) return PHRASES[trimmed];
  const spaced = trimmed.replace(/_/g, " ");
  if (PHRASES[spaced]) return PHRASES[spaced];
  let out = spaced;
  for (const key of PHRASE_KEYS) {
    if (!key.includes(" ")) continue;
    const escaped = key.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    out = out.replace(new RegExp(escaped, "g"), PHRASES[key]);
  }
  out = out.replace(/\bAM\b/g, "ص").replace(/\bPM\b/g, "م");
  out = out
    .split(/(\s+)/)
    .map((part) => PHRASES[part] ?? PHRASES[part.toLowerCase()] ?? part)
    .join("");
  return out.replace(/\s+/g, " ").trim();
}

function fill(template: string, vars?: Record<string, string | number>) {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? ""));
}

export type TFunction = (key: MessageKey, vars?: Record<string, string | number>) => string;

const LanguageContext = createContext<{
  lang: Lang;
  dir: "ltr" | "rtl";
  locale: string;
  dateLocale: Locale;
  setLang: (lang: Lang) => void;
  t: TFunction;
  known: (text: string) => string;
}>({
  lang: "en",
  dir: "ltr",
  locale: "en-GB",
  dateLocale: enUS,
  setLang: () => undefined,
  t: (key, vars) => fill(en[key], vars),
  known: (text) => text,
});

function readStoredLang(): Lang {
  try {
    return localStorage.getItem(STORAGE_KEY) === "ar" ? "ar" : "en";
  } catch {
    return "en";
  }
}

function applyLang(lang: Lang) {
  document.documentElement.lang = lang === "ar" ? "ar" : "en";
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");

  useEffect(() => {
    const next = readStoredLang();
    setLangState(next);
    applyLang(next);
  }, []);

  const value = useMemo(() => {
    const setLang = (next: Lang) => {
      setLangState(next);
      try {
        localStorage.setItem(STORAGE_KEY, next);
      } catch {
        /* ignore */
      }
      applyLang(next);
    };
    const dict = lang === "ar" ? ar : en;
    const t: TFunction = (key, vars) => fill(dict[key], vars);
    return {
      lang,
      dir: lang === "ar" ? ("rtl" as const) : ("ltr" as const),
      locale: lang === "ar" ? "ar-SA-u-nu-latn" : "en-GB",
      dateLocale: lang === "ar" ? arMonths : enUS,
      setLang,
      t,
      known: (text: string) => translateLabel(text, lang),
    };
  }, [lang]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useI18n() {
  return useContext(LanguageContext);
}

export function LanguageToggle({ className }: { className?: string }) {
  const { lang, setLang, t } = useI18n();
  const next: Lang = lang === "en" ? "ar" : "en";
  return (
    <button
      type="button"
      onClick={() => setLang(next)}
      aria-label={t("switchLanguageTitle")}
      title={t("switchLanguageTitle")}
      className={
        className ??
        "h-9 min-w-9 px-2.5 rounded-full bg-card/70 border border-border grid place-items-center text-xs font-semibold text-muted-foreground hover:text-foreground hover:border-primary/50 transition"
      }
    >
      {t("switchLanguage")}
    </button>
  );
}
